#!/usr/bin/env python3
"""Independent supplementary annulus pair: equal R3 but unequal full support.

No imports from the old or primary checkers.  All 10 x 1024 cells, including
empties, are regenerated by Cartesian-product enumeration.  --write creates
its target exclusively; --check compares the complete deterministic JSON.
"""
import argparse
from collections import Counter
import itertools
import json
from pathlib import Path

B = tuple(range(5))
U = tuple(range(5, 10))
C = tuple(range(4))
TAUS = tuple(itertools.product(C, repeat=5))


def require(condition, message):
    if not condition:
        raise ValueError(message)


def canonical(colors):
    names = {}
    return tuple(names.setdefault(c, len(names)) for c in colors)


def cyclic_proper(colors):
    return all(colors[i] != colors[(i + 1) % 5] for i in B)


BETAS = tuple(sorted({canonical(t) for t in TAUS if cyclic_proper(t)}))


def geometry(vertices, edges, faces):
    require(faces[0] == [4, 3, 2, 1, 0], 'outer orientation')
    darts = Counter((f[i], f[(i + 1) % len(f)])
                    for f in faces for i in range(len(f)))
    require(darts == Counter(d for a, b in edges for d in [(a, b), (b, a)]),
            'face darts')
    rotations = {}
    for x in vertices:
        pairs = [(f[i-1], f[(i+1) % len(f)])
                 for f in faces for i, y in enumerate(f) if x == y]
        link = dict(pairs)
        require(len(link) == len(pairs), 'repeated link input')
        require(set(link) == set(link.values()), 'link not permutation')
        start = min(link)
        seen, current = [], start
        while current not in seen:
            seen.append(current)
            current = link[current]
        require(current == start and len(seen) == len(link), 'split link')
        rotations[str(x)] = seen
    require(len(vertices) - len(edges) + len(faces) == 2, 'Euler')
    # Prove connectedness and absence of a cut vertex, without assuming either.
    for deleted in [None] + list(vertices):
        remaining = set(vertices) - {deleted}
        seen, todo = set(), [min(remaining)]
        while todo:
            x = todo.pop()
            if x in seen:
                continue
            seen.add(x)
            todo.extend(y for e in edges if x in e for y in e
                        if y in remaining and y not in seen)
        require(seen == remaining, 'disconnected or cut vertex')
    return {'darts': sum(darts.values()), 'euler_characteristic': 2,
            'two_connected': True, 'rotation': rotations,
            'score': 'triggered and holds'}


def valid(vertices, edges, lift):
    coloring = dict(zip(vertices, lift))
    return all(coloring[a] != coloring[b] for a, b in edges)


def enumerate_all(vertices, edges, beta):
    require(tuple(vertices[:5]) == B, 'B prefix')
    return [list(beta + tail) for tail in itertools.product(C, repeat=len(vertices)-5)
            if valid(vertices, edges, beta + tail)]


def graph_record(apex):
    vertices = list(range(10)) + ([11] if apex else [])
    edges = {tuple(sorted((i, (i+1) % 5))) for i in B}
    edges |= {tuple(sorted((5+i, 5+(i+1) % 5))) for i in B}
    edges |= {(0, 5), (1, 6)}
    faces = [[4, 3, 2, 1, 0], [5, 6, 7, 8, 9], [0, 1, 6, 5]]
    if apex:
        edges |= {(u, 11) for u in U}
        faces += [[1, 2, 3, 4, 0, 5, 11, 6], [11, 5, 9],
                  [11, 9, 8], [11, 8, 7], [11, 7, 6]]
    else:
        faces += [[1, 2, 3, 4, 0, 5, 9, 8, 7, 6]]
    edges = sorted(edges)
    gvertices = sorted(vertices + [10])
    gedges = sorted(edges + [(u, 10) for u in U])
    gfaces = [faces[0]] + faces[2:] + [[10, 5+i, 5+(i+1) % 5] for i in B]
    require([e for e in edges if set(e) <= set(U)] ==
            sorted(tuple(sorted((5+i, 5+(i+1) % 5))) for i in B), 'induced U')
    require({a for a, b in gedges if b == 10} == set(U), 'center neighbors')
    record = {'id': 'two_spoke_external_apex' if apex else 'two_spoke',
              'h_vertices': vertices, 'h_edges': edges, 'h_faces': faces,
              'h_geometry': geometry(vertices, edges, faces),
              'g_vertices': gvertices, 'g_edges': gedges, 'g_faces': gfaces,
              'g_geometry': geometry(gvertices, gedges, gfaces), 'rows': []}
    for beta in BETAS:
        hlifts = enumerate_all(vertices, edges, beta)
        glifts = enumerate_all(gvertices, gedges, beta)
        cells = [[] for _ in TAUS]
        for lift in hlifts:
            index = sum(lift[5+i] * 4**(4-i) for i in B)
            cells[index].append(lift)
        reconstructed = []
        for tau, fibre in zip(TAUS, cells):
            if len(set(tau)) != 3:
                continue
            center = min(set(C) - set(tau))
            for lift in fibre:
                coloring = dict(zip(vertices, lift))
                coloring[10] = center
                reconstructed.append([coloring[x] for x in gvertices])
        require(sorted(reconstructed) == glifts, 'cap reconstruction')
        record['rows'].append({'beta': beta, 'cells': cells, 'g_lifts': glifts,
                               'h_count': len(hlifts), 'g_count': len(glifts)})
    return record


def support(graph, size):
    return {(i, j) for i, row in enumerate(graph['rows'])
            for j, (tau, fibre) in enumerate(zip(TAUS, row['cells']))
            if fibre and (size is None or len(set(tau)) == size)}


def generate():
    graphs = [graph_record(False), graph_record(True)]
    first, second = graphs
    require(support(first, 3) == support(second, 3), 'unequal R3')
    require(support(first, None) != support(second, None), 'equal full support')
    require(not support(second, 4), 'external apex admits four colors')
    transfer_counts = []
    for source, target in [graphs, graphs[::-1]]:
        count = 0
        for i, row in enumerate(source['rows']):
            for lift in row['g_lifts']:
                coloring = dict(zip(source['g_vertices'], lift))
                tau = tuple(coloring[u] for u in U)
                index = sum(tau[k] * 4**(4-k) for k in B)
                candidate = min(target['rows'][i]['cells'][index])
                destination = dict(zip(target['h_vertices'], candidate))
                destination[10] = coloring[10]
                require(all(destination[p] == coloring[p] for p in B + U + (10,)),
                        'transfer changed a named pin or center')
                require(valid(target['g_vertices'], target['g_edges'],
                              [destination[x] for x in target['g_vertices']]),
                        'invalid transferred coloring')
                count += 1
        transfer_counts.append({'source': source['id'], 'target': target['id'],
                                'complete_g_lifts': count,
                                'score': 'triggered and holds'})
    beta, tau = (0, 1, 0, 1, 2), (1, 0, 1, 2, 3)
    ri, ti = BETAS.index(beta), TAUS.index(tau)
    require(first['rows'][ri]['cells'][ti] and not second['rows'][ri]['cells'][ti],
            'four-color witness')
    totals = [{'id': g['id'], 'support': len(support(g, None)),
               'R3': len(support(g, 3)), 'R4': len(support(g, 4)),
               'h_lifts': sum(r['h_count'] for r in g['rows']),
               'g_lifts': sum(r['g_count'] for r in g['rows']),
               'sigma_g': [bool(r['g_lifts']) for r in g['rows']]}
              for g in graphs]
    return {'schema': 'w5-three-support-supplementary-strictness-v1',
            'scope': 'Two new explicit plane annuli, separate from the old 34 controls',
            'B': B, 'U': U, 'center': 10, 'colors': C,
            'beta_domain': BETAS, 'tau_domain': TAUS, 'graphs': graphs,
            'summary': {'explicit_cells': 2*len(BETAS)*len(TAUS), 'graphs': totals,
                        'R3_equal': True, 'full_support_equal': False,
                        'geometry': 'triggered and holds',
                        'strictness': 'counterexample', 'transfers': transfer_counts,
                        'witness': {'beta': beta, 'tau': tau,
                                    'first_fibre': first['rows'][ri]['cells'][ti],
                                    'second_fibre': second['rows'][ri]['cells'][ti]},
                        'limits': ['Not claimed near-triangulated or a minimal source',
                                   'No general small representative constructed']}}


def main():
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group()
    group.add_argument('--write', type=Path)
    group.add_argument('--check', type=Path)
    args = parser.parse_args()
    result = generate()
    encoded = json.dumps(result, sort_keys=True, separators=(',', ':')) + '\n'
    if args.write:
        with args.write.open('x') as handle:
            handle.write(encoded)
    if args.check:
        require(args.check.read_text() == encoded, 'complete certificate mismatch')
    print(json.dumps(result['summary'], ensure_ascii=False, sort_keys=True, indent=2))


if __name__ == '__main__':
    main()

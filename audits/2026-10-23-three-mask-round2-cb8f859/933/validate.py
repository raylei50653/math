#!/usr/bin/env python3
"""Exclusive-create replay receipts, source-algorithm cross-check and negatives."""
import ast
from concurrent.futures import ThreadPoolExecutor
import copy
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
from unittest.mock import patch

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[2]
RUNS=HERE/'runs'
RUNS.mkdir(exist_ok=True)


def write_json(path,value):
    with path.open('x') as f:json.dump(value,f,indent=2,sort_keys=True);f.write('\n')


def run(name,extra=(),seed=None,expected=0):
    env=dict(os.environ)
    if seed is not None:env['PYTHONHASHSEED']=str(seed)
    command=[sys.executable,str(HERE/'check.py'),*extra]
    result=subprocess.run(command,cwd=ROOT,env=env,capture_output=True,text=True)
    with (RUNS/(name+'.stdout')).open('x') as f:f.write(result.stdout)
    with (RUNS/(name+'.stderr')).open('x') as f:f.write(result.stderr)
    assert result.returncode==expected,(name,result.returncode,result.stderr)
    return {'name':name,'command':command,'PYTHONHASHSEED':seed,'exit_code':result.returncode,
            'stdout_sha256':hashlib.sha256(result.stdout.encode()).hexdigest(),
            'stderr_sha256':hashlib.sha256(result.stderr.encode()).hexdigest()}


cert=json.loads((HERE/'certificate-v2.json').read_text())
bad=copy.deepcopy(cert);bad['pin_order'][1]='L'
write_json(RUNS/'negative-certificate.json',bad)
jobs=[('normal',(),None,0),('seed17',(),17,0),('negative',('--negative',),None,0),
      ('negative-file',('--certificate',str(RUNS/'negative-certificate.json')),None,1)]
with ThreadPoolExecutor(max_workers=4) as executor:
    replays=list(executor.map(lambda args:run(*args),jobs))
assert (RUNS/'normal.stdout').read_bytes()==(RUNS/'seed17.stdout').read_bytes()

spec=importlib.util.spec_from_file_location('round2check',HERE/'check.py')
c=importlib.util.module_from_spec(spec);spec.loader.exec_module(c)
manifest=c.inputs()
source=json.loads(c.frozen(c.SOURCE));tuples=list(map(tuple,source['tuples']))
fours=list(c.itertools.combinations(range(8),4))
nc=[p for p in c.partitions() if not any(p[i]==p[k] and p[j]==p[l] and p[i]!=p[j] for i,j,k,l in fours)]
algorithm=c.frozen('audits/2026-10-18-smaller-bad-e1617a2/kempe_consistency.py').decode()
tree=ast.parse(algorithm)
body=[n for n in tree.body if isinstance(n,ast.FunctionDef) and n.name=='options']
assert len(body)==1
namespace={'NONCROSSING':nc,'INDEX':dict(zip(tuples,range(274))),'canonical':c.canonical}
exec(compile(ast.Module(body=body,type_ignores=[]),'original-frozen-Kempe-options','exec'),namespace)
cross=[]
for key,records in cert['component_options'].items():
    old=namespace['options'](tuples[int(key)],c.SPLIT)
    assert [tuple(r['orbit']) for r in records]==[orbit for orbit,_ in old] or \
           sorted(tuple(r['orbit']) for r in records)==[orbit for orbit,_ in old]
    assert sorted((tuple(r['orbit']),tuple(r['partition'])) for r in records)==old
    cross.append({'tuple_id':int(key),'exact_original_options_agree':True,'partition_count':len(records)})

# Simulate byte drift without editing any sealed authority.
first=manifest['files'][0]['path'];original_frozen=c.frozen
def corrupted_frozen(path):
    data=original_frozen(path)
    return data+b'\n' if path==first else data
with patch.object(c,'frozen',corrupted_frozen):
    try:c.inputs()
    except AssertionError as exc:assert str(exc)=='frozen bytes: '+first
    else:raise AssertionError('accepted frozen-input drift')
fake_root=RUNS/'negative-authority-root';fake_path=fake_root/first
fake_path.parent.mkdir(parents=True,exist_ok=True)
with fake_path.open('xb') as f:f.write(original_frozen(first)+b'\n')
with patch.object(c,'ROOT',fake_root):
    try:c.inputs()
    except AssertionError as exc:assert str(exc)=='immutable authority drift: '+first
    else:raise AssertionError('accepted current authority drift')
c.inputs()

receipt={'ok':True,'base':c.BASE,'replays':replays,'normal_seed17_stdout_equal':True,
         'original_frozen_Kempe_algorithm_crosscheck':cross,
         'negative_controls_in_normal_checker':14,
         'negative_external_certificate_exit':1,'negative_frozen_byte_drift_rejected':True,
         'negative_current_authority_drift_rejected':True,
         'immutable_input_files':len(manifest['files']),'immutable_input_drift':0,
         'actual_source_control':'not triggered','source_realization_claimed':False,
         'strict_smaller_bad_constructed':False,'general_933_exclusion_claimed':False,
         'new_Lean_theorem':False}
write_json(HERE/'VERIFICATION.json',receipt)
# These are only bytecode generated by imports in this exclusive output tree.
for cache in HERE.rglob('__pycache__'):shutil.rmtree(cache)
print(json.dumps({'ok':True,'replays':len(replays),'negative_controls':16,'original_options_crosschecked':3,'immutable_input_drift':0},sort_keys=True))
